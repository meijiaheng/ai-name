create table if not exists public.name_history (
  id            bigint generated by default as identity primary key,
  user_requirement text not null,
  name_result      text not null,
  model_name       text not null,
  created_at       timestamp with time zone default now()
);

comment on table public.name_history is 'AI 起名历史：需求、生成结果、使用的模型';

-- 常用查询走创建时间，加个索引
create index if not exists name_history_created_at_idx
  on public.name_history (created_at desc);

-- ------------------------------------------------------------
-- 权限：实验阶段放开匿名读写（等价于“临时关闭 RLS 的效果”，但保留 RLS 开关）
-- 正式上线请改成带身份校验的策略，见 README「正式上线的权限方案」
-- ------------------------------------------------------------
alter table public.name_history enable row level security;

drop policy if exists "anon can insert name history" on public.name_history;
create policy "anon can insert name history"
  on public.name_history for insert
  to anon
  with check (true);

drop policy if exists "anon can read name history" on public.name_history;
create policy "anon can read name history"
  on public.name_history for select
  to anon
  using (true);

